#!/usr/bin/env node
/**
 * T001 environment probe.
 *
 * Prints tool versions, OS/CPU/RAM/disk facts and Chromium availability,
 * writes a deterministic report to evidence/environment/ENVIRONMENT_REPORT.md,
 * and exits 0 when the probe itself completes (missing optional tools are
 * recorded as NOT_FOUND, not treated as a probe failure).
 *
 * Determinism contract: the report file contains no timestamps, no machine
 * absolute paths, and no random values. The canonical fingerprint JSON covers
 * only stable facts (versions, OS, CPU model/count, total RAM, total disk,
 * tool availability); volatile values (free RAM/disk) are printed to stdout
 * only. Re-running this script on an unchanged environment must reproduce
 * the same fingerprint SHA-256.
 */
import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPORT_PATH = path.join(
  ROOT,
  "evidence",
  "environment",
  "ENVIRONMENT_REPORT.md",
);

function run(cmd) {
  try {
    return execSync(cmd, {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      timeout: 15000,
    }).trim();
  } catch {
    return "NOT_FOUND";
  }
}

function commandExists(name) {
  return run(`command -v ${name}`) !== "NOT_FOUND";
}

function osPrettyName() {
  try {
    const text = fs.readFileSync("/etc/os-release", "utf8");
    const line = text
      .split("\n")
      .find((l) => l.startsWith("PRETTY_NAME="));
    return line ? line.split("=")[1].replace(/^"|"$/g, "") : "unknown";
  } catch {
    return "unknown";
  }
}

function chromiumAvailable() {
  const inPath = ["chromium", "chromium-browser", "google-chrome"].some(
    commandExists,
  );
  if (inPath) return true;
  const home = os.homedir();
  const candidates = ["/opt/meta-chromium/chrome"];
  try {
    const pwDir = path.join(home, ".cache", "ms-playwright");
    for (const entry of fs.readdirSync(pwDir)) {
      if (entry.startsWith("chromium-")) {
        candidates.push(path.join(pwDir, entry, "chrome-linux", "chrome"));
      }
    }
  } catch {
    // No Playwright browser cache; not an error for this probe.
  }
  return candidates.some((p) => {
    try {
      return fs.existsSync(p);
    } catch {
      return false;
    }
  });
}

function gitStatus() {
  // `git rev-parse --git-dir` works even with zero commits, unlike
  // `rev-parse HEAD` / `--abbrev-ref HEAD`, which fail before the first commit.
  const gitDir = run("git rev-parse --git-dir");
  if (gitDir === "NOT_FOUND") {
    return { branch: "NOT_A_GIT_REPO", clean: null, head: "NOT_A_GIT_REPO", untracked_or_modified_count: 0 };
  }
  const porcelain = run("git status --porcelain");
  const branch = run("git symbolic-ref --short HEAD");
  const head = run("git rev-parse --short HEAD");
  return {
    branch: branch === "NOT_FOUND" ? "UNKNOWN" : branch,
    clean: porcelain === "" ? true : porcelain === "NOT_FOUND" ? null : false,
    head: head === "NOT_FOUND" ? "NO_COMMITS" : head,
    untracked_or_modified_count:
      porcelain === "" || porcelain === "NOT_FOUND"
        ? 0
        : porcelain.split("\n").filter(Boolean).length,
  };
}

function main() {
  const cpus = os.cpus();
  const statfs = fs.statfsSync(ROOT);
  const totalDiskBytes = statfs.bsize * statfs.blocks;

  const fingerprint = {
    arch: os.arch(),
    chromium_available: chromiumAvailable(),
    cpu_count: cpus.length,
    cpu_model: cpus.length > 0 ? cpus[0].model : "unknown",
    docker_available: commandExists("docker"),
    git: run("git --version"),
    node: run("node --version"),
    npm: run("npm --version"),
    os_pretty_name: osPrettyName(),
    os_release: os.release(),
    os_type: os.type(),
    platform: os.platform(),
    python: run("python --version"),
    python3: run("python3 --version"),
    total_disk_bytes: totalDiskBytes,
    total_memory_bytes: os.totalmem(),
  };

  const canonical = JSON.stringify(fingerprint, Object.keys(fingerprint).sort(), 2);
  const fingerprintSha256 = createHash("sha256").update(canonical).digest("hex");

  const git = gitStatus();

  const report = [
    "# P021 ViewportShift — Environment Report (T001)",
    "",
    "Generated by `scripts/env-check.mjs`. This report contains no timestamps,",
    "no machine absolute paths, and no random values. Re-running",
    "`npm run env:check` on an unchanged environment must reproduce the same",
    "fingerprint SHA-256 below. Volatile values (free RAM / free disk) are",
    "printed to stdout only and are intentionally absent from this file.",
    "",
    "## Environment fingerprint (canonical JSON)",
    "",
    "```json",
    canonical,
    "```",
    "",
    `**Fingerprint SHA-256:** \`${fingerprintSha256}\``,
    "",
    "## Tool versions",
    "",
    `| Tool | Version |`,
    `| --- | --- |`,
    `| Node | \`${fingerprint.node}\` |`,
    `| npm | \`${fingerprint.npm}\` |`,
    `| Python (\`python\`) | \`${fingerprint.python}\` |`,
    `| Python 3 (\`python3\`) | \`${fingerprint.python3}\` |`,
    `| Git | \`${fingerprint.git}\` |`,
    "",
    "## Machine",
    "",
    `| Fact | Value |`,
    `| --- | --- |`,
    `| OS | \`${fingerprint.os_pretty_name}\` (${fingerprint.os_type} ${fingerprint.os_release}, ${fingerprint.platform}/${fingerprint.arch}) |`,
    `| CPU | \`${fingerprint.cpu_model}\` × ${fingerprint.cpu_count} |`,
    `| Total RAM | ${fingerprint.total_memory_bytes} bytes |`,
    `| Total disk (workspace filesystem) | ${fingerprint.total_disk_bytes} bytes |`,
    `| Chromium available | ${fingerprint.chromium_available} |`,
    `| Docker available | ${fingerprint.docker_available} |`,
    "",
    "## Git worktree at probe time",
    "",
    `| Fact | Value |`,
    `| --- | --- |`,
    `| Branch | \`${git.branch}\` |`,
    `| HEAD | \`${git.head}\` |`,
    `| Clean | ${git.clean} |`,
    `| Changed/untracked entries | ${git.untracked_or_modified_count} |`,
    "",
    "## Notes",
    "",
    "- `python` (bare) is NOT installed on this VM; `python3` is the",
    "  interpreter to use. Downstream tasks must invoke `python3`.",
    "- Chromium is available (Playwright browser cache / system Chrome",
    "  binary detected); no system Chromium package is on PATH.",
    "- No GPU, Docker, phone, or external API is required for T001.",
    "- License status: `PENDING_SAM_DECISION`; no LICENSE file added.",
    "",
  ].join("\n");

  fs.mkdirSync(path.dirname(REPORT_PATH), { recursive: true });
  fs.writeFileSync(REPORT_PATH, report);

  const out = {
    ...fingerprint,
    fingerprint_sha256: fingerprintSha256,
    free_memory_bytes: os.freemem(),
    git,
    report: "evidence/environment/ENVIRONMENT_REPORT.md",
  };
  console.log(JSON.stringify(out, null, 2));
}

main();
